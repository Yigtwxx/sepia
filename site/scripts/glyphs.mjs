// Outlines of IBM Plex Mono 500 for the printable ASCII characters, so the mark
// (src/lib/emblem.ts) draws its characters as shapes: the same in the nav, in a
// browser tab and in a PNG, with no font to wait for or to fall back from.
//
//   node scripts/glyphs.mjs      (npm run glyphs)
//
// Writes src/data/glyphs.generated.ts: per character its path, in font units
// (1000 to the em, y down, origin on the baseline at the left edge).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';

const font = opentype.parse(
    readFileSync(
        fileURLToPath(
            new URL(
                '../node_modules/@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-500-normal.woff',
                import.meta.url,
            ),
        ),
    ).buffer,
);
const glyphs = {};
for (let code = 33; code < 127; code++) {
    const char = String.fromCharCode(code);
    const d = font.getPath(char, 0, 0, font.unitsPerEm).toPathData(0);
    if (d) glyphs[char] = d;
}
const out = new URL('../src/data/glyphs.generated.ts', import.meta.url);
writeFileSync(
    out,
    `/* Generated by scripts/glyphs.mjs from IBM Plex Mono 500: do not edit. */\n` +
        `export const UNITS_PER_EM = ${font.unitsPerEm};\n` +
        `export const ADVANCE = ${font.charToGlyph('M').advanceWidth};\n` +
        `export const glyphs: Record<string, string> = ${JSON.stringify(glyphs)};\n`,
);
console.log(`${Object.keys(glyphs).length} glyphs, ${font.unitsPerEm} units to the em`);
